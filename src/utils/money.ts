// Утилиты округления сумм. Вынесены в отдельный модуль без зависимостей,
// чтобы разорвать циклический импорт calculations ↔ wheely (единая точка правды).

// Округляем копейки до целых рублей (в большую или меньшую сторону — по математическим правилам).
// Это исключает «хвосты» вида 1234.5 из-за процентных долей (30/35/70%).
export const roundRubles = (v: number): number => Math.round(v);

// Безопасное приведение любого значения к конечному числу (null/undefined/NaN/строки → 0).
// Единый нормализатор для всех модулей расчёта.
export const num = (v: unknown): number => {
  const n = typeof v === 'number' ? v : Number(v);
  return Number.isFinite(n) ? n : 0;
};
